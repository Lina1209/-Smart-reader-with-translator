'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('function makeRtf(value){');
const end=html.indexOf('function makeFb2',start);
assert.ok(start>=0&&end>start,'RTF export helper must exist');
const context={String};
vm.createContext(context);
vm.runInContext(html.slice(start,end)+';globalThis.makeRtf=makeRtf;',context);
const rtf=context.makeRtf('Текст {в скобках} \\ путь\r\nВторая строка\tтабуляция 😀');
assert.ok(rtf.startsWith('{\\rtf1\\ansi\\deff0\\uc1'),'RTF document header must be present');
assert.ok(rtf.includes('\\u1058?'),'Cyrillic must be encoded as RTF Unicode');
assert.ok(rtf.includes('\\{\\u1074?')&&rtf.includes('\\u1093?\\}'),'Braces must be escaped around Unicode text');
assert.ok(rtf.includes(String.fromCharCode(92,92)+' путь'),'Backslashes must be escaped');
assert.ok(rtf.includes('\\par\n\\u1042?\\u1090?'),'CRLF must become one RTF paragraph break');
assert.ok(rtf.includes('\\tab \\u1090?'),'Tabs must use the RTF tab control');
assert.ok(rtf.includes('\\u-10179?\\u-8704?'),'Emoji surrogate pair must be retained as UTF-16 RTF Unicode units');
const controls=context.makeRtf('A\u0001B');
assert.ok(controls.includes('\\u1?'),'Unsupported control characters must not be emitted raw');
console.log('RTF export integrity tests passed: Unicode, escaping, CRLF, tabs and control characters.');
