'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('function getEpubNavigationAvailability(');
const end=html.indexOf('\n}',start)+2;
assert.ok(start>=0&&end>start,'EPUB navigation availability helper must exist');
const context={};
vm.createContext(context);
vm.runInContext(html.slice(start,end)+';globalThis.getAvailability=getEpubNavigationAvailability;',context);
const availability=(location,busy=false)=>JSON.parse(JSON.stringify(context.getAvailability(location,busy)));
assert.deepEqual(availability({page:1,total:5,atStart:true,atEnd:false}),{previousDisabled:true,nextDisabled:false});
assert.deepEqual(availability({page:5,total:5,atStart:false,atEnd:true}),{previousDisabled:false,nextDisabled:true});
assert.deepEqual(availability({page:1,total:1,atStart:true,atEnd:true}),{previousDisabled:true,nextDisabled:true});
assert.deepEqual(availability({page:1,total:1,atStart:false,atEnd:false}),{previousDisabled:false,nextDisabled:false},'section-local page counters must not disable navigation across chapter boundaries');
assert.deepEqual(availability({page:1,total:5,atStart:false,atEnd:false},true),{previousDisabled:true,nextDisabled:true},'both controls must lock while navigation is in progress');
assert.deepEqual(availability({page:1,total:5}),{previousDisabled:true,nextDisabled:false},'legacy or incomplete location data should retain safe page-counter fallback');
assert.deepEqual(availability({page:5,total:5}),{previousDisabled:false,nextDisabled:true});
console.log('EPUB navigation boundary tests passed');
