'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('function epubPositionKey(file){');
const end=html.indexOf('\nlet epubPositionStorageKey',start);
assert.ok(start>=0&&end>start,'EPUB position persistence helpers must exist');
const source=html.slice(start,end);
function makeContext(storage){
 const window={localStorage:storage};
 const context={window,Date,console};
 vm.createContext(context);
 vm.runInContext(source+';globalThis.key=epubPositionKey;globalThis.read=readEpubPosition;globalThis.save=saveEpubPosition;',context);
 return context;
}
const values=new Map();
const storage={getItem:key=>values.has(key)?values.get(key):null,setItem:(key,value)=>values.set(key,value)};
const context=makeContext(storage);
const file={name:'Novel.epub',size:12345,lastModified:1700000000000};
const key=context.key(file);
assert.equal(context.save(key,{start:{cfi:'epubcfi(/6/4[chapter2]!/4/2:10)'}}),true,'valid EPUB CFI must be saved');
assert.equal(context.read(key),'epubcfi(/6/4[chapter2]!/4/2:10)','saved reading position must be restored');
assert.notEqual(context.key({...file,name:'Different.epub'}),key,'different books must not share a reading position');
assert.notEqual(context.key({...file,size:12346}),key,'changed file size must invalidate the old book identity');
assert.notEqual(context.key({...file,lastModified:1700000000001}),key,'changed modification time must invalidate the old book identity');
assert.equal(context.save(key,{start:{cfi:'not-a-cfi'}}),false,'invalid CFI must not be persisted');
values.set(key,'{broken json');
assert.equal(context.read(key),'','corrupted storage must safely fall back to the beginning');
values.set(key,JSON.stringify({cfi:'javascript:alert(1)'}));
assert.equal(context.read(key),'','non-EPUB CFI values must be rejected');
const throwingStorage={getItem(){throw Error('storage disabled')},setItem(){throw Error('quota exceeded')}};
const safe=makeContext(throwingStorage);
assert.equal(safe.read('key'),'','blocked storage reads must not crash the reader');
assert.equal(safe.save('key',{start:{cfi:'epubcfi(/6/2)'}}),false,'storage write failures must not crash the reader');
console.log('EPUB position persistence tests passed: book identity, valid CFI restore, corrupted data, and unavailable storage are handled safely.');
