'use strict';
const assert=require('node:assert/strict');
const {paginateByHeight}=require('../lib/reader-pagination');
const height=(text)=>Math.ceil(Array.from(text).length/8);
const source='Intro abcdefghijklmnopqrstuvwxyz tail';
const result=paginateByHeight(source,height,2);
assert.ok(result.pages.length>1,'long unbroken token should span multiple pages');
assert.ok(result.pages.every(page=>height(page)<=2),'no page may exceed the measured height');
assert.equal(result.pages.join(''),source,'all original characters must be preserved in order');
assert.deepEqual(result.pages.map((page,i)=>source.slice(result.offsets[i],result.offsets[i+1]??source.length)),result.pages,'page offsets must point to exact source slices');
assert.ok(result.offsets.every((offset,i)=>Number.isInteger(offset)&&offset>=0&&(i===0||offset>result.offsets[i-1])),'page offsets must be increasing source positions');
const unicode='Начало супердлинноесловобезпробелов😀😀 конец';
const unicodeResult=paginateByHeight(unicode,height,2);
assert.ok(unicodeResult.pages.every(page=>height(page)<=2));
assert.equal(unicodeResult.pages.join(''),unicode,'Unicode and whitespace must be preserved');
assert.deepEqual(paginateByHeight('   ',height,2),{pages:[],offsets:[]});
const graphemeSource='x👩🏽‍💻🇰🇿e\u0301y';
const segmenter=new Intl.Segmenter(undefined,{granularity:'grapheme'});
const expectedGraphemes=Array.from(segmenter.segment(graphemeSource),part=>part.segment);
const graphemeOffsets=Array.from(segmenter.segment(graphemeSource),part=>part.index);
const graphemeHeight=text=>Array.from(segmenter.segment(text)).length;
const graphemeResult=paginateByHeight(graphemeSource,graphemeHeight,1);
assert.deepEqual(graphemeResult.pages,expectedGraphemes,'pagination must never split emoji ZWJ sequences, skin tones, regional-indicator flags or combining marks');
assert.deepEqual(graphemeResult.offsets,graphemeOffsets,'grapheme-safe page offsets must remain UTF-16 source offsets');
assert.equal(graphemeResult.pages.join(''),graphemeSource,'grapheme-safe pagination must preserve the exact source text');
assert.equal(paginateByHeight('one two three four',text=>text.length,5).pages.join('|'),'one |two |three| four','whitespace and page content should remain stable');
const {findPageIndexForOffset}=require('../lib/reader-pagination');
const offsets=[0,12,28,45];
assert.equal(findPageIndexForOffset(offsets,0),0);
assert.equal(findPageIndexForOffset(offsets,11),0);
assert.equal(findPageIndexForOffset(offsets,12),1,'exact page boundary must restore to that page');
assert.equal(findPageIndexForOffset(offsets,27),1);
assert.equal(findPageIndexForOffset(offsets,28),2);
assert.equal(findPageIndexForOffset(offsets,999),3,'offsets past the end must clamp to the last page');
assert.equal(findPageIndexForOffset([],25),0,'empty pagination must restore to the first page');
assert.throws(()=>paginateByHeight('x',height,0),TypeError);
console.log('Reader pagination long-token tests passed');
